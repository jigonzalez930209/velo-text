#!/usr/bin/env node
/** Pack fonts/ofl/*.ttf → src/fonts/ofl-bytes.ts (build-time, zero runtime fs). */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const oflDir = path.join(root, "fonts", "ofl");
const out = path.join(root, "src", "fonts", "ofl-bytes.ts");

const FILES = {
  "sans-regular": "LiberationSans-Regular.ttf",
  "sans-bold": "LiberationSans-Bold.ttf",
  "sans-italic": "LiberationSans-Italic.ttf",
  "sans-boldItalic": "LiberationSans-BoldItalic.ttf",
  "serif-regular": "LiberationSerif-Regular.ttf",
  "serif-bold": "LiberationSerif-Bold.ttf",
  "serif-italic": "LiberationSerif-Italic.ttf",
  "serif-boldItalic": "LiberationSerif-BoldItalic.ttf",
  "mono-regular": "LiberationMono-Regular.ttf",
  "mono-bold": "LiberationMono-Bold.ttf",
  "mono-italic": "LiberationMono-Italic.ttf",
  "mono-boldItalic": "LiberationMono-BoldItalic.ttf",
  "display-regular": "LiberationSansNarrow-Regular.ttf",
  "display-bold": "LiberationSansNarrow-Bold.ttf",
  "display-italic": "LiberationSansNarrow-Italic.ttf",
  "display-boldItalic": "LiberationSansNarrow-BoldItalic.ttf",
};

const lines = [
  "/** Generated by scripts/pack-ofl-fonts.js — do not edit. */",
  "export type OflFontKey =",
  `  ${Object.keys(FILES).map((k) => `"${k}"`).join(" | ")};`,
  "",
  "export const OFL_FONT_BYTES: Record<OflFontKey, Uint8Array> = {",
];

for (const [key, file] of Object.entries(FILES)) {
  const p = path.join(oflDir, file);
  if (!fs.existsSync(p)) {
    console.error(`[pack-ofl] missing ${p}`);
    process.exit(1);
  }
  const buf = fs.readFileSync(p);
  lines.push(`  "${key}": new Uint8Array([${[...buf].join(",")}]),`);
}
lines.push("};", "");
fs.writeFileSync(out, lines.join("\n"));
console.log(`[pack-ofl] wrote ${out} (${Object.keys(FILES).length} fonts)`);
